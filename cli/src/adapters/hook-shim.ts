// The one small script Cursor and Gemini CLI hooks go through (.cursor/hooks/groundwork.mjs,
// .gemini/hooks/groundwork.mjs). Neither tool takes a hook's plain-text output as model context:
// Cursor wants {"additional_context"} / {"followup_message"} JSON, Gemini CLI wants
// {"hookSpecificOutput":{"additionalContext"}} / {"decision":"deny","reason"} JSON, and Gemini CLI treats
// any non-JSON stdout as a message for the user. So the script runs Groundwork's own hook scripts
// (.groundwork/hooks/session-start.mjs and checkpoint.mjs, with the contract's arguments) and puts
// their text in the shape the tool reads. It never fails the tool: any error prints nothing.
// With the flow it also runs the guards (Cursor only; Gemini CLI runs .groundwork/guards/run.mjs itself).
export type ShimTool = "cursor" | "gemini";

// Per tool: how the hook's input is normalized for Groundwork's scripts, and how text goes back.
const TOOLS: Record<ShimTool, { input: string; reply: Record<string, string> }> = {
  cursor: {
    // Cursor's stop input has a loop_count, not stop_hook_active; the conversation id is the session.
    input: `{ ...raw, session_id: raw.session_id ?? raw.conversation_id, stop_hook_active: Number(raw.loop_count) > 0 }`,
    reply: {
      "session-start": `text ? { additional_context: text } : {}`,
      stop: `text ? { followup_message: text } : {}`,
      // preCompact can only show the user a message and sessionEnd's output is unused: checkpoint only.
      "pre-compact": `{}`,
      "session-end": `{}`,
    },
  },
  gemini: {
    input: `raw`,
    reply: {
      "session-start": `text ? { hookSpecificOutput: { hookEventName: "SessionStart", additionalContext: text } } : {}`,
      stop: `text ? { decision: "deny", reason: text } : {}`,
      // PreCompress only accepts a message for the user, and SessionEnd is best effort: checkpoint only.
      "pre-compress": `{}`,
      "session-end": `{}`,
    },
  },
};

const GUARD_CURSOR = `
  if (event === "guard") {
    // Fails closed: Cursor's hook has failClosed, an exit code of 2 blocks, and so does silence.
    try {
      const guards = join(project, ".groundwork", "guards");
      const { evaluate } = await import(pathToFileURL(join(guards, "run.mjs")).href);
      const result = await evaluate("cursor", input, guards);
      for (const warning of result.warnings ?? []) process.stderr.write(warning + "\\n");
      out(result.block ? { permission: "deny", user_message: result.reason, agent_message: result.reason } : { permission: "allow" });
    } catch (error) {
      process.stderr.write("Groundwork's guards couldn't run (" + error.message + "), so this call is blocked. Run groundwork doctor.\\n");
      process.exitCode = 2;
    }
    return;
  }`;

// Event names the script takes as its first argument, per tool.
export const SHIM_EVENTS: Record<ShimTool, string[]> = {
  cursor: ["session-start", "stop", "pre-compact", "session-end"],
  gemini: ["session-start", "stop", "pre-compress", "session-end"],
};

export function hookShim(tool: ShimTool, flow: boolean, sources: string[]): string {
  const spec = TOOLS[tool];
  const label = tool === "cursor" ? "Cursor" : "Gemini CLI";
  const guard = flow && tool === "cursor";
  const replies = Object.entries(spec.reply)
    .map(([event, expr]) => `  "${event}": (text) => (${expr}),`)
    .join("\n");
  return `// Groundwork hook script for ${label}. Generated by Groundwork; edit .groundwork/hooks/ instead.
// Usage: node ${tool === "cursor" ? ".cursor" : ".gemini"}/hooks/groundwork.mjs <${SHIM_EVENTS[tool].join("|")}${guard ? "|guard" : ""}>
// It runs .groundwork/hooks/session-start.mjs and checkpoint.mjs and returns their text in the JSON
// ${label} reads (${sources.join("; ")}).
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath${guard ? ", pathToFileURL" : ""} } from "node:url";

// This file lives in <project>/${tool === "cursor" ? ".cursor" : ".gemini"}/hooks/, so the project is two folders up.
const project = fileURLToPath(new URL("../../", import.meta.url));
const TOOL = "${tool}";

const REPLY = {
${replies}
};

function hookInput() {
  try {
    return JSON.parse(readFileSync(0, "utf8").replace(/^\\uFEFF/, "") || "{}");
  } catch {
    return {};
  }
}

const out = (value) => process.stdout.write(JSON.stringify(value) + "\\n");

// Runs one of Groundwork's hook scripts with the hook's input on stdin; "" if it says nothing or fails.
function run(script, args, input) {
  const file = join(project, ".groundwork", "hooks", script);
  if (!existsSync(file)) return "";
  try {
    return execFileSync(process.execPath, [file, ...args], {
      input: JSON.stringify(input),
      encoding: "utf8",
      timeout: 10000,
      windowsHide: true,
      stdio: ["pipe", "pipe", "ignore"],
    }).trim();
  } catch {
    return "";
  }
}

async function main() {
  const event = process.argv[2] ?? "";
  const raw = hookInput();
  const input = ${spec.input};
${guard ? GUARD_CURSOR : ""}
  const reply = REPLY[event];
  if (!reply) return;
  try {
    const text = event === "session-start" ? run("session-start.mjs", [project, TOOL], input) : run("checkpoint.mjs", [event === "pre-compress" ? "pre-compact" : event, project, TOOL], input);
    out(reply(event === "session-start" || event === "stop" ? text : ""));
  } catch {
    // a hook never stops the tool
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
`;
}
