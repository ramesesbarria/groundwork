// OpenCode adapter. Formats from opencode.ai/docs (commands, agents, tools, rules), checked 2026-09-24.
// OpenCode reads AGENTS.md itself, so no extra rules file is needed.
import type { CoreFiles } from "../core.js";
import { commandsOf, modelFor, sortedByPath, subagentRolesOf, yamlValue, type ModelHints } from "./shared.js";

// OpenCode permission keys each role's subagent is denied. "edit" covers edit, write and apply_patch.
const ROLE_DENY: Record<string, string[]> = {
  tester: [],
  implementer: [],
  reviewer: ["edit"],
};

// The plugin a project gets: one file, whichever layers it has. With the flow it keeps the name 1.x
// used, so an upgrade replaces that file; `flow on` and `flow off` swap one for the other.
export const OPENCODE_FLOW_PLUGIN = ".opencode/plugins/groundwork-guards.js";
export const OPENCODE_MEMORY_PLUGIN = ".opencode/plugins/groundwork-memory.js";

const HEAD_FLOW = `// Groundwork: runs the guards listed in .groundwork/config.json before each tool call, records the
// human's own messages for the commit gate, tells each session where the project stands (the project
// brief, from .groundwork/), and saves a checkpoint when a session goes idle or is compacted.
// Throwing an error blocks the call. Generated by Groundwork; edit .groundwork/guards/ instead.`;

const HEAD_MEMORY = `// Groundwork: tells each session where the project stands (the project brief, from .groundwork/),
// and saves a checkpoint when a session goes idle or is compacted.
// Generated by Groundwork; it only runs the scripts in .groundwork/hooks/.`;

const IMPORTS_FLOW = `import { Plugin } from "@opencode/plugin";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";`;

const IMPORTS_MEMORY = `import { Plugin } from "@opencode/plugin";
import { existsSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";`;

// Runs Groundwork's guards before each tool call (throwing blocks the call).
// OpenCode 2.x plugin format: Plugin.define({ id, setup }), with hooks registered on the context.
// (A 2.0.32 `run --standalone` check also loaded the older { id, setup } default export.) Guards checked
// against 2.0.16 on 2026-09-25.
const GUARDS = `    const guardsDir = join(project, ".groundwork", "guards");
    let runner;
    try {
      runner = await import(pathToFileURL(join(guardsDir, "run.mjs")).href);
    } catch (error) {
      console.warn("Groundwork: guards couldn't load (" + error.message + "). Commits stay blocked; run groundwork doctor.");
    }

    // The runner fails safe: if it couldn't load, block commits and leave other calls alone.
    await context.tool.hook("execute.before", async (event) => {
      if (!runner) {
        const toolName = String(event.tool ?? "");
        if (["write", "edit", "patch", "apply_patch"].includes(toolName)) {
          throw new Error("[protect-harness] Groundwork's guards couldn't load, so writes are blocked. Run groundwork doctor.");
        }
        const command = String(event.input?.command ?? "");
        if (
          (toolName === "shell" || toolName === "bash") &&
          /\\bgit\\b[\\s\\S]*\\bcommit\\b|\\.groundwork[\\\\/](?:guards|hooks|lib|\\.approvals|config|\\.legacy)|\\.opencode[\\\\/]plugins|\\b(?:uninstall|migrate)\\b|user-prompt\\.mjs/i.test(command)
        ) {
          throw new Error("[commit-gate] Groundwork's guards couldn't load, so this call is blocked. Run groundwork doctor.");
        }
        console.warn("Groundwork: guards couldn't load, so this call isn't checked. Run groundwork doctor.");
        return;
      }
      const result = await runner.evaluate("opencode", { tool: event.tool, args: event.input ?? {} }, guardsDir);
      for (const warning of result.warnings) console.warn(warning);
      if (result.block) throw new Error(result.reason);
    });
`;

// Project memory, in every install.
// Session start: the "context" session hook adds the project brief to the system prompt, like Claude
// Code's SessionStart hook. Its system entries must be { type: "text", text } (checked against 2.0.18
// on 2026-09-26). It runs for each model call, so the brief is rebuilt at most every 15 seconds.
// Checkpoints, from opencode.ai/v2/docs/build/plugins/server and .../migrate-v1 (read 2026-11-15; not
// yet run against a live OpenCode):
//   - the "compaction" session hook "runs for checkpoint summaries"; it has the context hook's fields,
//     so what the summary must keep is pushed onto \`system\` the same way;
//   - there is no idle or session-end hook. \`context.event.subscribe()\` yields the event stream, and
//     \`session.idle\` is the event the migration guide uses for "session completed".
// A hook can't speak at idle, so a reminder to save the handoff is added to the next model call.
// Each registration is on its own: an OpenCode without one of these hooks keeps the others.
const MEMORY = `    let reminder = "";
    let model;
    try {
      const hook = join(project, ".groundwork", "hooks", "session-start.mjs");
      const orientation = existsSync(hook) ? (await import(pathToFileURL(hook).href)).orientation : undefined;
      let brief = { at: 0, text: "" };
      // Groundwork's own subagents get their task from the runner, so they skip it.
      await context.session.hook("context", async (input) => {
        if (!orientation || String(input.agent ?? "").startsWith("gw-")) return;
        model = input.model?.id ?? model;
        if (Date.now() - brief.at > 15000) brief = { at: Date.now(), text: await orientation(project) };
        if (brief.text) input.system.push({ type: "text", text: brief.text });
        if (reminder) {
          input.system.push({ type: "text", text: reminder });
          reminder = "";
        }
      });
    } catch (error) {
      console.warn("Groundwork: the session-start brief isn't available (" + error.message + ").");
    }

    let stop;
    try {
      const saver = join(project, ".groundwork", "hooks", "checkpoint.mjs");
      const { onEvent } = existsSync(saver) ? await import(pathToFileURL(saver).href) : {};
      if (typeof onEvent === "function") {
        try {
          await context.session.hook("compaction", async (event) => {
            try {
              const { say } = onEvent(project, "pre-compact", { tool: "opencode", session: event?.sessionID, model: event?.model?.id ?? model });
              if (say && Array.isArray(event?.system)) event.system.push({ type: "text", text: say });
            } catch {
              // a checkpoint never stops a compaction
            }
          });
        } catch {
          console.warn("Groundwork: this OpenCode has no compaction hook, so compactions aren't checkpointed.");
        }
        try {
          const controller = new AbortController();
          stop = () => controller.abort();
          void (async () => {
            try {
              for await (const event of context.event.subscribe({ types: ["session.idle"], signal: controller.signal })) {
                if (event?.type !== "session.idle") continue;
                try {
                  const { say } = onEvent(project, "stop", { tool: "opencode", model });
                  if (say) reminder = say;
                } catch {
                  // a checkpoint never stops the session
                }
              }
            } catch {
              // the event stream ended or isn't available: sessions just aren't checkpointed when idle
            }
          })();
        } catch {
          console.warn("Groundwork: this OpenCode has no event stream, so idle sessions aren't checkpointed.");
        }
      }
    } catch (error) {
      console.warn("Groundwork: checkpoints aren't available (" + error.message + ").");
    }
`;

// Records the human's own messages for the commit gate. The "prompt" session hook fires for top-level
// prompts and for subagent prompts in child sessions, which the hook skips by parentID so a spawned
// agent can't record an approval. A typed message arrives as typed; a custom command arrives as its
// expanded template, with no command name (2.1.0, 2026-10-20), hence RECORDED_COMMANDS below.
const RECORDER = `
    // Records the human's messages, like Claude Code's UserPromptSubmit hook. Prompt admission
    // fires for prompts the user (or a command) submits; synthetic messages don't run it. The
    // "records-human" marker is written on the first real message, proving the signal live: only
    // then does the commit gate demand the approvals marker, so a tool without this hook keeps
    // the card checks only.
    try {
      const recorder = join(project, ".groundwork", "hooks", "user-prompt.mjs");
      const { recordHuman } = existsSync(recorder) ? await import(pathToFileURL(recorder).href) : {};
      if (typeof recordHuman === "function") {
        await context.session.hook("prompt", async (event) => {
          try {
            // The task tool delivers subagent instructions as prompts in child sessions; only the
            // human's own messages arrive in a top-level one. Without this, anything that can spawn
            // a subagent could forge an approval.
            const session = await context.session.get({ sessionID: event?.sessionID });
            if (session?.parentID) return;
            recordHuman(project, event?.prompt?.text ?? "");
            const approvals = join(project, ".groundwork", ".approvals");
            mkdirSync(approvals, { recursive: true });
            writeFileSync(join(approvals, "records-human"), JSON.stringify({ tool: "opencode", at: new Date().toISOString() }, null, 2) + "\\n");
          } catch {
            // Best effort: the gate then only checks the card.
          }
        });
      } else if (existsSync(recorder)) {
        console.warn("Groundwork: .groundwork/hooks/user-prompt.mjs doesn't export recordHuman, so the commit gate will check the card only.");
      }
    } catch {
      console.warn("Groundwork: the prompt hook isn't available (OpenCode version or .groundwork/hooks), so the commit gate will check the card only.");
    }
`;

const plugin = (flow: boolean) => `${flow ? HEAD_FLOW : HEAD_MEMORY}
${flow ? IMPORTS_FLOW : IMPORTS_MEMORY}

// This file lives in <project>/.opencode/plugins/, so the project is two folders up.
const project = fileURLToPath(new URL("../../", import.meta.url));

export default Plugin.define({
  id: "${flow ? "groundwork-guards" : "groundwork-memory"}",
  async setup(context) {
${flow ? `${GUARDS}\n` : ""}${MEMORY}${flow ? RECORDER : ""}
    return stop;
  },
});
`;

// Commands the prompt hook records (.groundwork/hooks/user-prompt.mjs).
const RECORDED_COMMANDS = new Set(["gw-approve", "gw-reject"]);

// Pure: core files in, OpenCode files out. Generated files point to the core instead of copying it.
// `flow` adds the flow's subagents, guards and approval recorder to the context layer's plugin.
export function generateOpenCode(core: CoreFiles, models: ModelHints = {}, flow = "guards/run.mjs" in core): Record<string, string> {
  const out: Record<string, string> = {};

  for (const { name, description } of commandsOf(core)) {
    out[`.opencode/commands/${name}.md`] = [
      "---",
      `description: ${yamlValue(description)}`,
      "---",
      // OpenCode 2.1 hands the prompt hook the expanded template, not what the human typed (checked
      // 2026-10-20). The approval recorder reads the command from the first line, so these two
      // templates start with it.
      ...(RECORDED_COMMANDS.has(name) ? [`/${name} $ARGUMENTS`, ""] : []),
      `Read \`.groundwork/commands/${name}.md\` now and follow it exactly.`,
      "",
      "Arguments: $ARGUMENTS",
      "",
    ].join("\n");
  }

  for (const { name: role, description } of flow ? subagentRolesOf(core) : []) {
    const deny = ROLE_DENY[role];
    if (!deny) throw new Error(`No OpenCode permissions defined for role "${role}"`);
    const model = modelFor(models, role, "opencode");
    out[`.opencode/agents/gw-${role}.md`] = [
      "---",
      `description: ${yamlValue(description)}`,
      "mode: subagent",
      ...(model ? [`model: ${yamlValue(model)}`] : []),
      ...(deny.length > 0 ? ["permission:", ...deny.map((key) => `  ${key}: deny`)] : []),
      "---",
      `You are the Groundwork ${role}. Read \`.groundwork/roles/${role}.md\` now and follow it exactly.`,
      "Load only the files it lists under Load.",
      "",
    ].join("\n");
  }

  out[flow ? OPENCODE_FLOW_PLUGIN : OPENCODE_MEMORY_PLUGIN] = plugin(flow);

  return sortedByPath(out);
}
